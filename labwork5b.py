import numpy as np
import pandas as pd
df = pd.read_csv("students.csv")
df2 = pd.read_csv("scores.csv")
print("Check missing values")
print(df.isna().sum())
print(df2.isna().sum())
print("Fill or remove missing data appropriately")
df = df.dropna()
df2 = df2.dropna()
print("Merge the two datasets")
df3 = pd.merge(df, df2, on="student_id")
print("Calculate each student's average score")
df3["average_score"] = df3[["python", "math", "database"]].mean(axis=1)
df4 = pd.merge(df, df3, on="student_id")
print("Find the top 5 students")
top_5_students = df3.sort_values("average_score", ascending=False).head(5)
print(top_5_students)
print("Compute average score by major")
avg_score_by_major = df3.groupby("major")["average_score"].mean()
print(avg_score_by_major)